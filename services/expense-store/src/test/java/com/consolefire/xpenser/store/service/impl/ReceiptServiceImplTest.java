package com.consolefire.xpenser.store.service.impl;

import static org.assertj.core.api.Assertions.assertThat;

import com.consolefire.xpenser.store.data.dto.request.ReceiptRequestDto;
import com.consolefire.xpenser.store.data.dto.response.ReceiptResponseDto;
import com.consolefire.xpenser.store.data.entity.ReceiptEntity;
import com.consolefire.xpenser.store.data.mapper.ReceiptMapper;
import com.consolefire.xpenser.store.PostgresTestcontainersTest;
import com.consolefire.xpenser.store.data.repository.ReceiptRepository;
import com.consolefire.xpenser.store.exception.ReceiptExistsException;
import com.fasterxml.jackson.databind.ObjectMapper;
import com.fasterxml.jackson.datatype.jsr310.JavaTimeModule;
import jakarta.persistence.EntityManager;
import java.io.IOException;
import java.io.InputStream;
import java.time.Instant;
import java.util.Optional;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.autoconfigure.EnableAutoConfiguration;
import org.springframework.boot.autoconfigure.jdbc.DataSourceAutoConfiguration;
import org.springframework.boot.autoconfigure.jdbc.DataSourceTransactionManagerAutoConfiguration;
import org.springframework.boot.autoconfigure.orm.jpa.HibernateJpaAutoConfiguration;
import org.springframework.boot.test.autoconfigure.jdbc.AutoConfigureTestDatabase;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.core.io.ClassPathResource;
import org.springframework.test.context.ActiveProfiles;
import reactor.core.publisher.Mono;
import reactor.test.StepVerifier;

@SpringBootTest

@ActiveProfiles("test")
@DisplayName("ReceiptServiceImpl Integration Tests")
class ReceiptServiceImplTest implements PostgresTestcontainersTest {

    @Autowired
    private ReceiptServiceImpl receiptService; // The service we are testing

    @Autowired
    private ReceiptRepository receiptRepository; // To interact with the actual DB

    @Autowired
    private ReceiptMapper receiptMapper; // The real mapper, no longer mocked

    @Autowired
    private EntityManager entityManager; // For managing test state (clearing DB)

    private ObjectMapper objectMapper; // For reading JSON test data

    @BeforeEach
    void setUp() {
        // Clear the database before each test
        entityManager.createNativeQuery("TRUNCATE TABLE receipts CASCADE;").executeUpdate();
        entityManager.flush();
        entityManager.clear();

        // Initialize ObjectMapper for JSON deserialization
        objectMapper = new ObjectMapper();
        objectMapper.registerModule(new JavaTimeModule()); // Support for Java 8 Date/Time types
    }

    /**
     * Helper method to read the test.receipt.json file and deserialize it into a ReceiptRequestDto.
     */
    private ReceiptRequestDto readReceiptRequestDtoFromJson(String filename) throws IOException {
        ClassPathResource resource = new ClassPathResource("com/consolefire/xpenser/store/service/impl/" + filename);
        try (InputStream inputStream = resource.getInputStream()) {
            return objectMapper.readValue(inputStream, ReceiptRequestDto.class);
        }
    }

    @Test
    @DisplayName("Should create a new receipt successfully from JSON data")
    void shouldCreateReceiptSuccessfullyFromJson() throws IOException {
        // Given
        // Read the request DTO directly from the JSON file
        ReceiptRequestDto requestDto = readReceiptRequestDtoFromJson("test.receipt.json");

        // When
        // Call the real service method
        Mono<ReceiptResponseDto> resultMono = receiptService.createReceipt(requestDto);

        // Then
        // Verify the response from the service
        StepVerifier.create(resultMono)
            .expectNextMatches(response -> {
                assertThat(response).isNotNull();
                assertThat(response.getReceiptId()).isNotNull(); // ID should be generated by DB
                assertThat(response.getIdentifier()).isEqualTo(requestDto.getIdentifier());
                assertThat(response.getCreatedAt()).isNotNull(); // Auditing fields should be populated

                // Verify the receipt was actually saved in the database
                Optional<ReceiptEntity> foundInDb = receiptRepository.findByUniqueKey(
                    requestDto.getIdentifier(), requestDto.getMarketPlaceCode(), requestDto.getStoreCode());
                assertThat(foundInDb).isPresent();
                assertThat(foundInDb.get().getId()).isEqualTo(response.getReceiptId());
                assertThat(foundInDb.get().getGeneratedAt()).isEqualTo(
                    requestDto.getTimestamp()); // Verify timestamp mapping
                assertThat(foundInDb.get().getPayment()).isNotNull();
                assertThat(foundInDb.get().getItems()).isNotEmpty();
                return true;
            })
            .verifyComplete();
    }


    @Test
    @DisplayName("Should throw ReceiptExistsException if receipt already exists from JSON data")
    void shouldThrowExceptionIfReceiptExistsFromJson() throws IOException {
        // Given
        // Read the request DTO from the JSON file
        ReceiptRequestDto requestDto = readReceiptRequestDtoFromJson("test.receipt.json");

        // Use the real mapper to convert DTO to entity for pre-populating DB
        ReceiptEntity entityToSave = receiptMapper.toEntity(requestDto);
        // It's crucial to set auditing fields or ensure they're handled by the DB/JPA listeners
        entityToSave.setCreatedAt(Instant.now());
        entityToSave.setCreatedBy("test_system");
        entityToSave.setUpdatedAt(Instant.now());
        entityToSave.setUpdatedBy("test_system");

        // Ensure relationships are set up for persistence if not handled by mapper's lifecycle
        // This is important if your mapper doesn't fully link children back to parent entities
        if (entityToSave.getPayment() != null) {
            entityToSave.getPayment().setReceipt(entityToSave);
            if (entityToSave.getPayment().getTax() != null) {
                entityToSave.getPayment().getTax().setPayment(entityToSave.getPayment());
                entityToSave.getPayment().getTax().getTaxDetails()
                    .forEach(td -> td.setTax(entityToSave.getPayment().getTax()));
            }
        }
        entityToSave.getItems().forEach(item -> item.setReceipt(entityToSave));

        // Pre-populate the database with an existing receipt having the same unique key
        receiptRepository.save(entityToSave);
        entityManager.flush();
        entityManager.clear(); // Clear persistence context to ensure fresh load

        // When & Then
        // Attempt to create the receipt again, expecting an exception
        StepVerifier.create(receiptService.createReceipt(requestDto))
            .expectErrorMatches(e -> e instanceof ReceiptExistsException &&
                e.getMessage().contains(
                    String.format("Receipt with identifier '%s', marketplace '%s', and store '%s' already exists.",
                        requestDto.getIdentifier(), requestDto.getMarketPlaceCode(), requestDto.getStoreCode())))
            .verify();
    }


    @Test
    @DisplayName("Should handle null timestamp in request DTO and set current Instant from JSON data")
    void shouldSetGeneratedAtIfNullInDtoFromJson() throws IOException {
        // Given
        // Read the base DTO from JSON, then create a new DTO with null timestamp
        ReceiptRequestDto baseRequestDto = readReceiptRequestDtoFromJson("test.receipt.json");
        ReceiptRequestDto requestDtoWithNullTimestamp = baseRequestDto.toBuilder()
            .timestamp(null) // Set timestamp to null for this specific test
            .build();

        // When
        // Call the real service method with the modified DTO
        Mono<ReceiptResponseDto> resultMono = receiptService.createReceipt(requestDtoWithNullTimestamp);

        // Then
        // Verify the response and the saved entity in the database
        StepVerifier.create(resultMono)
            .expectNextMatches(response -> {
                assertThat(response).isNotNull();
                assertThat(response.getIdentifier()).isEqualTo(requestDtoWithNullTimestamp.getIdentifier());
                assertThat(response.getReceiptId()).isNotNull();

                // Verify that a receipt was saved and its generatedAt is not null
                Optional<ReceiptEntity> foundInDb = receiptRepository.findByUniqueKey(
                    requestDtoWithNullTimestamp.getIdentifier(),
                    requestDtoWithNullTimestamp.getMarketPlaceCode(),
                    requestDtoWithNullTimestamp.getStoreCode()
                );
                assertThat(foundInDb).isPresent();
                assertThat(foundInDb.get().getGeneratedAt()).isNotNull(); // It should be set by the service
                // Check that the timestamp is approximately the current time (within a few seconds)
                assertThat(foundInDb.get().getGeneratedAt()).isBetween(Instant.now().minusSeconds(5),
                    Instant.now().plusSeconds(5));
                return true;
            })
            .verifyComplete();
    }
}