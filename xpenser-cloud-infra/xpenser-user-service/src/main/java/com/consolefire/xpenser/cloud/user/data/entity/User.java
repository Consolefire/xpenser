package com.consolefire.xpenser.cloud.user.data.entity;

import java.time.Instant;
import java.util.Collection;
import java.util.HashSet;
import java.util.Set;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Data;
import lombok.EqualsAndHashCode;
import lombok.NoArgsConstructor;
import lombok.ToString;
import org.springframework.data.annotation.Id;
import org.springframework.data.annotation.Transient;
import org.springframework.data.relational.core.mapping.Table;
import org.springframework.security.core.GrantedAuthority;
import org.springframework.security.core.authority.SimpleGrantedAuthority;
import org.springframework.security.core.userdetails.UserDetails;

@Table("users")
@Data
@Builder
@NoArgsConstructor
@AllArgsConstructor
@EqualsAndHashCode(of = "username")
@ToString(exclude = "roles")
public class User implements UserDetails {

    @Id
    private Long id;

    private String username;
    private String password;
    private String email;
    private String firstName;
    private String lastName;
    private boolean enabled = true;
    private boolean accountNonExpired = true;
    private boolean credentialsNonExpired = true;
    private boolean accountNonLocked = true;
    private Instant createdAt = Instant.now();
    private Instant updatedAt = Instant.now();

    @Transient // R2DBC does not automatically map many-to-many. Fetch separately.
    private Set<Role> roles = new HashSet<>();

    public User(String username, String password, String email, String firstName, String lastName, Set<Role> roles) {
        this.username = username;
        this.password = password;
        this.email = email;
        this.firstName = firstName;
        this.lastName = lastName;
        this.roles = roles; // This will be set manually after fetching from join tables
    }

    @Override
    public Collection<? extends GrantedAuthority> getAuthorities() {
        Set<GrantedAuthority> authorities = new HashSet<>();
        roles.forEach(role -> authorities.add(new SimpleGrantedAuthority(role.getName())));
        roles.stream()
            .flatMap(role -> role.getPrivileges().stream())
            .map(privilege -> new SimpleGrantedAuthority(privilege.getName()))
            .forEach(authorities::add);
        return authorities;
    }

    // UserDetails methods (getters generated by Lombok)
}