package com.consolefire.xpenser.cloud.user.data.mapper;

import com.consolefire.xpenser.cloud.user.data.dto.UserRegistrationRequestDto;
import com.consolefire.xpenser.cloud.user.data.dto.UserResponseDto;
import com.consolefire.xpenser.cloud.user.data.dto.UserUpdateRequestDto;
import com.consolefire.xpenser.cloud.user.data.entity.User;
import java.util.Set;
import java.util.stream.Collectors;
import org.mapstruct.BeanMapping;
import org.mapstruct.Mapper;
import org.mapstruct.Mapping;
import org.mapstruct.MappingTarget;
import org.mapstruct.NullValuePropertyMappingStrategy;

@Mapper(componentModel = "spring") // Spring component for dependency injection
public interface UserMapper {

    @Mapping(target = "id", ignore = true) // ID is generated by DB
    @Mapping(target = "password", ignore = true) // Password is hashed in service
    @Mapping(target = "enabled", ignore = true)
    @Mapping(target = "accountNonExpired", ignore = true)
    @Mapping(target = "credentialsNonExpired", ignore = true)
    @Mapping(target = "accountNonLocked", ignore = true)
    @Mapping(target = "createdAt", ignore = true)
    @Mapping(target = "updatedAt", ignore = true)
    @Mapping(target = "roles", ignore = true)
        // Roles are assigned in service
    User toEntity(UserRegistrationRequestDto dto);

    @Mapping(target = "roles", expression = "java(mapRolesToNames(user))")
    @Mapping(target = "privileges", expression = "java(mapPrivilegesToNames(user))")
    UserResponseDto toDto(User user);

    @BeanMapping(nullValuePropertyMappingStrategy = NullValuePropertyMappingStrategy.IGNORE)
    @Mapping(target = "id", ignore = true)
    @Mapping(target = "username", ignore = true) // Username cannot be updated via this DTO
    @Mapping(target = "password", ignore = true) // Password not updated via this DTO
    @Mapping(target = "enabled", ignore = true)
    @Mapping(target = "accountNonExpired", ignore = true)
    @Mapping(target = "credentialsNonExpired", ignore = true)
    @Mapping(target = "accountNonLocked", ignore = true)
    @Mapping(target = "createdAt", ignore = true)
    @Mapping(target = "updatedAt", ignore = true) // Updated at handled manually
    @Mapping(target = "roles", ignore = true)
        // Roles handled separately
    void updateFromDto(UserUpdateRequestDto dto, @MappingTarget User user);

    // Helper methods for mapping collections to names
    default Set<String> mapRolesToNames(User user) {
        return user.getRoles().stream()
            .map(role -> role.getName())
            .collect(Collectors.toSet());
    }

    default Set<String> mapPrivilegesToNames(User user) {
        return user.getRoles().stream()
            .flatMap(role -> role.getPrivileges().stream())
            .map(privilege -> privilege.getName())
            .collect(Collectors.toSet());
    }
}